    [Fact]
    public async Task Regenerate_PreservesCustomItems()
    {
        var ingId    = await SeedIngredientAsync();
        var recipeId = await SeedRecipeAsync(ingId);
        var plan     = await CreatePlanViaApi();
        await AddRecipeToPlanAsync(plan.Id, recipeId);

        // Auto-generate first
        var listResponse = await Client.GetAsync("/api/v1/shopping-lists/active");
        var list = await listResponse.Content.ReadFromJsonAsync<ShoppingListResponse>();

        // Add custom item
        await Client.PostAsJsonAsync($"/api/v1/shopping-lists/{list!.Id}/items",
            new { name = "CustomBread", amount = (decimal?)null, unit = (string?)null, category = "OTHER" });

        // Regenerate
        var regenResponse = await Client.PostAsync("/api/v1/shopping-lists/active/generate", null);
        regenResponse.StatusCode.Should().Be(HttpStatusCode.OK);
        var regenerated = await regenResponse.Content.ReadFromJsonAsync<ShoppingListResponse>();

        regenerated!.Items.Should().Contain(i => i.IsCustom && i.DisplayName == "CustomBread");
    }

