namespace RecipeApp.Tests.Endpoints;

[Collection("Database")]
public class ShoppingListEndpointsTests(DatabaseFixture db) : IAsyncLifetime
{
    public ValueTask InitializeAsync() => db.TruncateAllAsync();
    public ValueTask DisposeAsync() => ValueTask.CompletedTask;

    private HttpClient Client => db.CreateClient();

    private async Task<Guid> SeedIngredientAsync(string name = "flour", string displayName = "Flour")
    {
        await using var ctx = db.CreateDbContext();
        var ing = TestDataBuilder.Ingredient(name, displayName);
        ctx.Ingredients.Add(ing);
        await ctx.SaveChangesAsync();
        return ing.Id;
    }

    private async Task<Guid> SeedRecipeAsync(Guid ingredientId, string name = "Test Recipe")
    {
        var request  = TestDataBuilder.CreateRecipeRequest(ingredientId, name);
        var response = await Client.PostAsJsonAsync("/api/v1/recipes", request);
        response.EnsureSuccessStatusCode();
        var recipe = await response.Content.ReadFromJsonAsync<API.DTOs.Recipes.RecipeDetailResponse>();
        return recipe!.Id;
    }

    private async Task<MealPlanDetailResponse> CreatePlanViaApi(string name = "Plan")
    {
        var response = await Client.PostAsJsonAsync("/api/v1/meal-plans", new { name });
        response.EnsureSuccessStatusCode();
        return (await response.Content.ReadFromJsonAsync<MealPlanDetailResponse>())!;
    }

    private async Task AddRecipeToPlanAsync(Guid planId, Guid recipeId)
    {
        var response = await Client.PostAsJsonAsync($"/api/v1/meal-plans/{planId}/planned-meals", new { recipeId });
        response.EnsureSuccessStatusCode();
    }

    // ── GET /shopping-lists/active ────────────────────────────────────────────

    [Fact]
    public async Task GetActive_NoActivePlan_Returns404()
    {
        var response = await Client.GetAsync("/api/v1/shopping-lists/active");
        response.StatusCode.Should().Be(HttpStatusCode.NotFound);
    }

    [Fact]
    public async Task GetActive_WithActivePlanAndRecipes_Returns200AutoGenerated()
    {
        var ingId    = await SeedIngredientAsync();
        var recipeId = await SeedRecipeAsync(ingId);
        var plan     = await CreatePlanViaApi();
        await AddRecipeToPlanAsync(plan.Id, recipeId);

        var response = await Client.GetAsync("/api/v1/shopping-lists/active");
        response.StatusCode.Should().Be(HttpStatusCode.OK);

        var list = await response.Content.ReadFromJsonAsync<ShoppingListResponse>();
        list.Should().NotBeNull();
        list!.Items.Should().NotBeEmpty();
        list.MealPlanId.Should().Be(plan.Id);
    }

    [Fact]
    public async Task GetActive_ListsEachGeneratedItemsSources()
    {
        var ingId    = await SeedIngredientAsync();
        var recipeId = await SeedRecipeAsync(ingId, "Pancakes");
        var plan     = await CreatePlanViaApi();
        await AddRecipeToPlanAsync(plan.Id, recipeId);

        using var json = JsonDocument.Parse(await Client.GetStringAsync("/api/v1/shopping-lists/active"));

        var source = json.RootElement.GetProperty("items")[0].GetProperty("sources").EnumerateArray().Single();
        source.GetProperty("recipeName").GetString().Should().Be("Pancakes");
        source.GetProperty("scheduledDate").ValueKind.Should().Be(JsonValueKind.Null);
        source.GetProperty("shareUnit").ValueKind.Should().Be(JsonValueKind.Null);
    }

    [Fact]
    public async Task GetActive_ReturnsIsStaleTrue_WhenPlanChangedAfterGeneration()
    {
        var ingId    = await SeedIngredientAsync();
        var recipeId = await SeedRecipeAsync(ingId);
        var plan     = await CreatePlanViaApi();
        await AddRecipeToPlanAsync(plan.Id, recipeId);

        // Generate list
        var firstResponse = await Client.GetAsync("/api/v1/shopping-lists/active");
        firstResponse.EnsureSuccessStatusCode();

        await Task.Delay(20);

        // Mutate the plan (add another recipe)
        var recipeId2 = await SeedRecipeAsync(ingId, "R2");
        await AddRecipeToPlanAsync(plan.Id, recipeId2);

        var staleResponse = await Client.GetAsync("/api/v1/shopping-lists/active");
        var staleList = await staleResponse.Content.ReadFromJsonAsync<ShoppingListResponse>();
        staleList!.IsStale.Should().BeTrue();
    }

